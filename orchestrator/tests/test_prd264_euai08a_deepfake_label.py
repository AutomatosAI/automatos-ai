def test_switching_the_label_off_changes_the_hash_and_sends_an_approved_post_back_for_approval():
    post = _approved_post()
    approved = post.content_hash
    deepfake_label.set_label(post, "member-1", False)
    assert post.content_hash == service.compute_content_hash(post) != approved
    assert post.status == service.NEEDS_APPROVAL and post.approved_hash != post.content_hash
    switched, voided = post.review_log[-2:]
    assert (switched["action"], switched["on"], switched["by"]) == ("ai_label", False, "member-1")
    assert switched["comment"] == deepfake_label.SWITCHED_OFF
    assert voided["action"] == service.ACTION_APPROVAL_VOIDED

    off_hash, entries = post.content_hash, len(post.review_log)
    deepfake_label.set_label(post, "member-1", False)  # what it is already: nothing changes
    assert (post.content_hash, len(post.review_log)) == (off_hash, entries)
    deepfake_label.set_label(post, "member-1", True)
    assert post.content_hash not in (off_hash, approved)  # a person's on is content too


def test_a_post_nobody_set_hashes_as_before():
    post = _approved_post()
    content = service._content_of(post)
    assert deepfake_label.FIELD not in content
    post.review_log = [*post.review_log, {"action": "render", "at": "2026-10-20T09:00:00+00:00"}]
    assert service.compute_content_hash(post) == post.content_hash
    assert deepfake_label.hashed(content, _post_of(log=[_switched(False)])) == {**content, "ai_label": False}


def test_the_switch_takes_a_flag_and_only_while_the_post_can_be_edited():
    post = _approved_post()
    with pytest.raises(service.InvalidPost):
        deepfake_label.set_label(post, "member-1", "off")
    post.status = service.RENDERING
    with pytest.raises(service.IllegalTransition):
        deepfake_label.set_label(post, "member-1", False)


