def _render_done(record):
    return {"at": "2026-10-20T09:00:00+00:00", "by": "member-1", "action": "render_done", "comment": None,
            "report": {"ai_media": record}}


def _switched(on):
    return {"at": "2026-10-20T09:05:00+00:00", "by": "member-1", "action": "ai_label", "comment": None, "on": on}


def _post_of(bundle=SPOKEN, footage=None, log=(), **fields):
    """A post as its render of ``bundle`` left it, with ``log`` after the render."""
    base = {
        "id": uuid.uuid4(), "workspace_id": uuid.uuid4(), "format": "video", "copy": {"base": BASE}, "title": "Countdown",
        "voice": None, "footage": footage, "media": RENDERED, "review_log": [], "targets": [],
    }
    made = SimpleNamespace(**{**base, **fields})
    record = ai_media.render_record(made, bundle, made.media)
    return SimpleNamespace(**{**vars(made), "review_log": [_render_done(record), *log]})


def _approved_post():
    post = service.create_draft(FakeDb(), workspace_id=uuid.uuid4(), created_by="member-1", title="Countdown",
                                copy={"base": BASE}, format="video")
    service.submit(post, "member-1")
    service.approve(post, "reviewer-1", content_hash=post.content_hash)
    return post


