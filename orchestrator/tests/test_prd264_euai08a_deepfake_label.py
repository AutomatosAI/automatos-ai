@pytest.mark.parametrize("toolkit, channel", [("linkedin", "LinkedIn"), ("twitter", "X"), ("instagram", "Instagram")])
def test_the_caption_channels_say_the_label_was_added_while_it_is_on(toolkit, channel):
    on = ai_media.label_line(toolkit, VOICE, {}, deepfake_label.caption_for({"base": BASE}, toolkit, True))
    assert on == (
        f"This post carries {WHAT}, and {channel} takes no AI label through its API, so the caption "
        "carries the disclosure: \"AI-generated.\" was added at its start."
    )
    off = ai_media.label_line(toolkit, VOICE, {}, deepfake_label.caption_for({"base": BASE}, toolkit, False))
    assert off == (
        f"This post carries {WHAT}, and {channel} takes no AI label through its API, so the caption "
        "carries the disclosure: start it with \"AI-generated.\""
    )
    chosen = ai_media.label_line(toolkit, ai_media.AiMedia(), {}, deepfake_label.caption_for({"base": BASE}, toolkit, True))
    assert chosen == "The post carries no AI media, and you chose to label it: \"AI-generated.\" starts its caption."


def test_the_receipt_shows_the_setting():
    name, seconds, interval = deepfake_label.SETTING_NAME, _cfg().SOCIALS_AI_LABEL_SECONDS, _cfg().SOCIALS_AI_LABEL_INTERVAL_SECONDS
    on = deepfake_label.summary(_post_of(), True, True)
    assert on["line"] == (
        f'{name}: on. The caption starts with "AI-generated." '
        f'The video shows "AI-generated" for its first {seconds:g} s and again every {interval:g} s.'
    )
    off = deepfake_label.summary(_post_of(log=[_switched(False)]), True, False)
    assert off["line"] == f"{name}: off for this post. You are responsible for disclosing deep fakes."
    assert off["reason"] == "You are responsible for disclosing deep fakes."
    stale = deepfake_label.summary(_post_of(log=[_switched(False)]), True, True)
    assert stale["line"].endswith("The video was rendered with the label on: render it again before it is approved.")

    targets = [SimpleNamespace(id=uuid.uuid4(), toolkit="twitter", post_kind="text", options={}, action_plan={})]
    answer = ai_media.labels_for(_post_of(targets=targets))
    assert answer["deepfake_label"]["line"].startswith(f"{name}: on.")
    assert answer["targets"][0]["ai_label"].endswith('"AI-generated." was added at its start.')


