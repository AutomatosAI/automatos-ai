def test_the_route_is_a_plain_def_in_the_manifest():
    routes = {route.path: route for route in socials_publish.router.routes if isinstance(route, APIRoute)}
    route = routes["/posts/{post_id}/ai-label"]
    assert route.methods == {"PUT"}
    assert not inspect.iscoroutinefunction(route.endpoint)  # F105
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    assert {"method": "PUT", "path": "/api/socials/posts/{post_id}/ai-label"} in manifest["routes"]
    assert manifest["route_count"] == len(manifest["routes"])


def test_the_route_takes_a_flag_in_the_callers_workspace_and_never_while_the_post_renders(env):
    post = _renderable(env)
    url = f"/api/socials/posts/{post['id']}/ai-label"
    assert env.client.put(url, json={"on": "off"}).status_code == 422
    assert env.client.put(url, json={"on": False, "label": "x"}).status_code == 422
    env.ctx = _ctx(WS_OTHER)
    assert env.client.put(url, json={"on": False}).status_code == 404
    env.ctx = _ctx(render_harness.WS)
    _start(env, post)  # rendering now
    assert env.client.put(url, json={"on": False}).status_code == 409
    assert deepfake_label.setting_of(_post(env, post["id"])) is None
