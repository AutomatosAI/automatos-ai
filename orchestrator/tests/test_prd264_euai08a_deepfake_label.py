def test_an_audio_only_post_opens_with_the_spoken_line():
    labelled = deepfake_label.with_spoken_line(SPOKEN)
    opening, line = labelled["audio"]["voice"]["lines"]
    assert opening == {"id": "ai-label", "at": 0, "text": "This audio was generated by AI."}
    assert line == {**SPOKEN["audio"]["voice"]["lines"][0], "at": round(0.3 + deepfake_label.SPOKEN_LEAD_SECONDS, 3)}
    assert SPOKEN["audio"]["voice"]["lines"][0]["at"] == 0.3  # a new copy: the bundle given is untouched
    assert LINE_ID.match(deepfake_label.SPOKEN_LINE_ID), "media-render takes the line's id"

    bundle = {**SPOKEN, ai_media.INPUTS: {"voice": True}}
    audio = SimpleNamespace(format="audio", copy={"base": BASE}, review_log=[])
    assert deepfake_label.with_label(bundle, audio)["audio"]["voice"]["lines"][0]["text"] == deepfake_label.SPOKEN_LINE
    video = SimpleNamespace(format="video", copy={"base": BASE}, review_log=[])
    assert deepfake_label.with_label(bundle, video)["audio"] == SPOKEN["audio"]  # a video shows its label instead
    silenced = SimpleNamespace(format="audio", copy={"base": BASE}, review_log=[_switched(False)])
    assert deepfake_label.with_label(bundle, silenced) == bundle


