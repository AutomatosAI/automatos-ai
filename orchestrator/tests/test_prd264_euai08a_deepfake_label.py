def test_a_labelled_posts_render_asks_media_render_for_the_label(env, monkeypatch):
    monkeypatch.setattr(_cfg(), "SOCIALS_AI_LABEL_SECONDS", 4.0)
    monkeypatch.setattr(_cfg(), "SOCIALS_AI_LABEL_INTERVAL_SECONDS", 20.0)
    post = _renderable(env)  # the harness template speaks one Kokoro line: AI media
    _, job = _start(env, post)
    renderer = Renderer()
    assert _run(job, renderer, FakeStore(), env.factory) is True
    (sent,) = renderer.bundles
    assert sent["ai_label"] == {"text": "AI-generated", "seconds": 4.0, "interval": 20.0}
    assert parse_ai_label(sent["ai_label"]) == AiLabel(text="AI-generated", seconds=4.0, interval=20.0)
    assert _post(env, post["id"]).review_log[-1]["report"]["ai_media"]["labelled"] is True


def test_a_switched_off_posts_render_asks_for_no_label(env):
    post = _renderable(env)
    resp = env.client.put(f"/api/socials/posts/{post['id']}/ai-label", json={"on": False})
    assert resp.status_code == 200, resp.text
    assert resp.json()["review_log"][-1]["action"] == "ai_label"
    _, job = _start(env, post)
    renderer = Renderer()
    assert _run(job, renderer, FakeStore(), env.factory) is True
    (sent,) = renderer.bundles
    assert "ai_label" not in sent
    assert _post(env, post["id"]).review_log[-1]["report"]["ai_media"]["labelled"] is False


