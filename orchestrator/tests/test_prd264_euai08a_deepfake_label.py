"""PRD-264 EUAI-08a (EU AI Act Art. 50(4)) — Socials labels realistic AI media as AI-generated, on by default.

``modules/socials/deepfake_label.py`` holds the rule. Pinned here:

* **the default follows the media**: a post carrying AI media (EUAI-05) is labelled, one
  without is not, and a person's switch wins; the newest ``ai_label`` entry of the post's
  review_log is the setting; no agent tool takes it, so Automatos's own posts use the default;
* **the setting is approved content**: switching it changes the content hash, so an
  approved post goes back for approval; setting it to what it is changes nothing; a post
  nobody set hashes as before;
* **the caption** starts with "AI-generated." in the post's language (en, pt, es, fr, de,
  it; English otherwise), once, fitted to the channel's limit;
* **the audio line**: an audio-only post opens with "This audio was generated by AI.";
* **the overlay parameters reach the render request** over the real render path (the
  US-104 harness: media-render over httpx.MockTransport), media-render's own parser reads
  them, a switched-off post's render asks for none, a still asks for none;
* **the receipt** shows the setting, and LinkedIn, X and Instagram say the caption label was
  added while it is on;
* **the route** ``PUT /api/socials/posts/{id}/ai-label``: a plain ``def`` in the manifest,
  the caller's workspace only, a true or false only, never while the post renders.

media-render burns the label in (``services/media-render/media_render/ai_label.py``); its
own suite reads the pixels back in the image (``services/media-render/tests/test_ai_label.py``).
"""
