def test_the_default_follows_the_posts_media_and_the_newest_switch_wins():
    spoken = _post_of(SPOKEN)  # Kokoro spoke its script: a synthetic voice
    assert ai_media.labels_for(spoken)["deepfake_label"]["on"] is True
    assert ai_media.labels_for(spoken)["deepfake_label"]["default"] is True
    own = _post_of(SILENT, footage={"photo": _done("upload", "image/png")}, format="image")
    assert ai_media.labels_for(own)["deepfake_label"]["on"] is False

    off = _post_of(SPOKEN, log=[_switched(True), {"action": "submit"}, _switched(False)])
    assert deepfake_label.setting_of(off) is False
    answer = ai_media.labels_for(off)["deepfake_label"]
    assert (answer["setting"], answer["default"], answer["on"]) == (False, True, False)
    assert deepfake_label.setting_of(_post_of(SPOKEN, log=[{"action": "ai_label", "on": "yes"}])) is None  # not a flag


def test_no_agent_tool_takes_the_setting_so_automatos_own_posts_use_the_default():
    """Agents create and edit through these request models (handlers_socials.py): neither has the field."""
