#!/usr/bin/env python3
"""Each of the API's lock files satisfies its input (PRD-262 US-022).

orchestrator/requirements.in, requirements-leiden.in (Railway's [leiden] build, until
US-027) and requirements-dev.txt are compiled with uv into requirements.lock,
requirements-leiden.lock and requirements-dev.lock, every pin with its hashes. The
image, CI and the OSS scanner install the locks, never the inputs, so a change to an
input that is not compiled into its lock would never be installed anywhere. This
check reads the files and nothing else: it never re-resolves against PyPI, so an
upstream release does not turn it red. For each lock it fails on:

- a header that is not the compile command in ``LOCKS`` (the flags: universal, Python
  3.11, wheels only but pysher and graspologic, hashes);
- a pin that is not ``==`` or carries no hash;
- a requirement of an input that the lock does not pin, or pins at a version the
  requirement excludes;
- a pin nothing needs: its ``# via`` names an input that no longer asks for it, or a
  package the lock does not pin, and nothing else (a removed requirement left behind);
- a pin shared with a lock it was compiled against (``-c``) or is installed with, at
  another version, or with no hash in common (pip checks every file's hashes), and,
  when that lock's inputs are among this one's, a package that lock pins and this one
  does not.

orchestrator/tests/test_prd262_api_locks.py runs it in the backend suite. By hand,
from the repository root, with ``packaging`` installed (requirements.lock has it):

    python3 scripts/ci/lock_check.py

Exit 0 when every lock satisfies its input, 1 otherwise.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path
from typing import Dict, FrozenSet, List, Mapping, NamedTuple, Tuple

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name
from packaging.version import Version

ROOT = Path(__file__).resolve().parents[2]
HEADER = "# This file was autogenerated by uv via the following command:"
FLAGS = ("--universal --python-version 3.11 --only-binary :all: --no-binary pysher,graspologic "
         "--generate-hashes")
_PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)\s*(===|==|~=|!=|>=|<=|>|<)?\s*([^\s;\\]*)")
_HASH = re.compile(r"--hash=sha256:([0-9a-f]{64})")
_COMMENT = re.compile(r"(?:^|\s)#.*$")


class Spec(NamedTuple):
    """One lock: its inputs, the locks it was compiled against, and those installed with it."""

    lock: str
    inputs: Tuple[str, ...]
    constraints: Tuple[str, ...] = ()
    installed_with: Tuple[str, ...] = ()

    @property
    def command(self) -> str:
        """The compile command the lock's header must carry, as run from the repository root."""
        constraints = "".join(f" -c {path}" for path in self.constraints)
        return f"uv pip compile {' '.join(self.inputs)}{constraints} {FLAGS} -o {self.lock}"


IN, LEIDEN_IN, DEV_IN = ("orchestrator/requirements.in", "orchestrator/requirements-leiden.in",
                         "orchestrator/requirements-dev.txt")
LOCK, LEIDEN_LOCK, DEV_LOCK = ("orchestrator/requirements.lock", "orchestrator/requirements-leiden.lock",
                               "orchestrator/requirements-dev.lock")
# In the order they are compiled: each one's constraints come before it.
LOCKS = (
    Spec(LOCK, (IN,)),
    Spec(LEIDEN_LOCK, (IN, LEIDEN_IN), constraints=(LOCK,)),
    # CI installs it with requirements.lock; the test image puts it on top of either build.
    Spec(DEV_LOCK, (DEV_IN,), constraints=(LOCK,), installed_with=(LEIDEN_LOCK,)),
)


class Pin(NamedTuple):
    """One ``name==version`` entry of a lock. ``via`` holds ``-r <file>``, ``-c <file>`` or package names."""

    name: str
    operator: str
    version: str
    hashes: FrozenSet[str]
    via: Tuple[str, ...]


def _via(comment: str) -> List[str]:
    """The sources one ``# via`` comment line names (``# via a`` or ``#   a``)."""
    body = comment.lstrip("#").strip()
    body = body.removeprefix("via").strip() if body == "via" or body.startswith("via ") else body
    return [body] if body else []


def parse_lock(text: str) -> Tuple[str, List[Pin]]:
    """(the compile command in the header, every pin). Pure."""
    lines = text.splitlines()
    command = lines[1].lstrip("#").strip() if len(lines) > 1 and lines[0] == HEADER else ""
    found: List[dict] = []
    for line in lines:
        if not line.strip() or (line.startswith("#") and not found):
            continue
        if not line[:1].isspace():
            match = _PIN.match(line)
            if not match:
                raise ValueError(f"not a pin: {line!r}")
            found.append({"name": canonicalize_name(match.group(1)), "operator": match.group(2) or "",
                          "version": match.group(3), "hashes": set(), "via": []})
        elif line.strip().startswith("#"):
            found[-1]["via"] += _via(line.strip())
        else:
            found[-1]["hashes"].update(_HASH.findall(line))
    return command, [Pin(item["name"], item["operator"], item["version"], frozenset(item["hashes"]),
                         tuple(item["via"])) for item in found]


def parse_input(text: str) -> List[Requirement]:
    """The requirements of an input file, comments and blank lines dropped. Pure.

    An option line (``-r``, ``-c``, ``--index-url``) raises ValueError: the check would
    otherwise skip what it names.
    """
    requirements = []
    for raw in text.splitlines():
        line = _COMMENT.sub("", raw).strip()
        if not line:
            continue
        if line.startswith("-"):
            raise ValueError(f"an option line this check does not follow: {line!r}")
        requirements.append(Requirement(line))
    return requirements


def _by_name(pins: List[Pin]) -> Dict[str, List[Pin]]:
    grouped: Dict[str, List[Pin]] = {}
    for pin in pins:
        grouped.setdefault(pin.name, []).append(pin)
    return grouped


def pin_problems(lock: str, pins: List[Pin]) -> List[str]:
    """Pins that are not exact or carry no hash."""
    problems = [f"{lock}: {pin.name} is not pinned with == ({pin.operator or 'no version'})"
                for pin in pins if pin.operator != "=="]
    problems += [f"{lock}: {pin.name}=={pin.version} carries no hash" for pin in pins if not pin.hashes]
    return problems if pins else [f"{lock}: pins nothing"]


def input_problems(spec: Spec, pins: List[Pin], inputs: Mapping[str, List[Requirement]]) -> List[str]:
    """Input requirements the lock does not pin, or pins at a version they exclude."""
    pinned, problems = _by_name(pins), []
    for path in spec.inputs:
        for requirement in inputs[path]:
            found = pinned.get(canonicalize_name(requirement.name), [])
            if not found:
                if requirement.marker is None:
                    problems.append(f"{spec.lock}: {path} asks for {requirement}, which the lock does not pin")
                continue
            wrong = [pin.version for pin in found if pin.operator == "=="
                     and not requirement.specifier.contains(Version(pin.version), prereleases=True)]
            if wrong:
                problems.append(f"{spec.lock}: pins {requirement.name} at {', '.join(wrong)}; "
                                f"{path} asks for {requirement}")
    return problems


def origin_problems(spec: Spec, pins: List[Pin], inputs: Mapping[str, List[Requirement]]) -> List[str]:
    """Pins whose ``# via`` no longer holds: a requirement or a package that is gone."""
    pinned = {pin.name for pin in pins}
    asked = {path: {canonicalize_name(req.name) for req in inputs[path]} for path in spec.inputs}
    problems = []
    for pin in pins:
        stale = [source for source in pin.via if source.startswith("-r ")
                 and pin.name not in asked.get(source[3:], set())]
        stale += [source for source in pin.via if not source.startswith("-")
                  and canonicalize_name(source) not in pinned]
        needed = [source for source in pin.via if not source.startswith("-c ") and source not in stale]
        if stale:
            problems.append(f"{spec.lock}: {pin.name}=={pin.version} is pinned for {', '.join(stale)}, "
                            "which no longer asks for it: recompile the lock")
        elif not needed:
            problems.append(f"{spec.lock}: nothing in {', '.join(spec.inputs)} needs "
                            f"{pin.name}=={pin.version}: recompile the lock")
    return problems


def agreement_problems(spec: Spec, pins: List[Pin], locks: Mapping[str, List[Pin]]) -> List[str]:
    """Shared pins that differ from a constraint or installed-with lock, and gaps in a superset."""
    mine, problems = _by_name(pins), []
    for other in spec.constraints + spec.installed_with:
        theirs = _by_name(locks[other])
        for name in sorted(mine.keys() & theirs.keys()):
            versions = ({pin.version for pin in mine[name]}, {pin.version for pin in theirs[name]})
            if versions[0] != versions[1]:
                problems.append(f"{spec.lock}: pins {name} at {', '.join(sorted(versions[0]))}, "
                                f"{other} at {', '.join(sorted(versions[1]))}")
            elif not set().union(*(p.hashes for p in mine[name])) & set().union(*(p.hashes for p in theirs[name])):
                problems.append(f"{spec.lock}: {name} shares no hash with {other}")
        if set(_spec(other).inputs) <= set(spec.inputs):
            problems += [f"{spec.lock}: lacks {name}, which {other} pins"
                         for name in sorted(theirs.keys() - mine.keys())]
    return problems


def _spec(lock: str) -> Spec:
    return next(spec for spec in LOCKS if spec.lock == lock)


def problems(files: Mapping[str, str]) -> List[str]:
    """Every problem with every lock in ``LOCKS``, from the files' texts by repository path. Pure."""
    parsed = {spec.lock: parse_lock(files[spec.lock]) for spec in LOCKS}
    pins = {lock: found for lock, (_, found) in parsed.items()}
    inputs = {path: parse_input(files[path]) for spec in LOCKS for path in spec.inputs}
    found: List[str] = []
    for spec in LOCKS:
        command, mine = parsed[spec.lock]
        if command != spec.command:
            found.append(f"{spec.lock}: the header says `{command}`, not `{spec.command}`")
        found += pin_problems(spec.lock, mine)
        found += input_problems(spec, mine, inputs)
        found += origin_problems(spec, mine, inputs)
        found += agreement_problems(spec, mine, pins)
    return found


def read_files(root: Path = ROOT) -> Dict[str, str]:
    """Every lock and input ``LOCKS`` names, read from ``root``."""
    paths = {spec.lock for spec in LOCKS} | {path for spec in LOCKS for path in spec.inputs}
    return {path: (root / path).read_text(encoding="utf-8") for path in sorted(paths)}


def main() -> int:
    found = problems(read_files())
    for problem in found:
        print(f"::error title=Lock does not satisfy its input (PRD-262 US-022)::{problem}")
    if not found:
        print(f"{len(LOCKS)} locks, each the compile of its input: "
              + ", ".join(spec.lock for spec in LOCKS))
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
