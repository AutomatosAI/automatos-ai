/**
 * PRD-261 A-01 — the theme-sdk shims (scripts/theme-sdk/generate-shims.js). The export lists are
 * read statically from the CommonJS builds Next vendors; here they are checked against what those
 * builds really export when loaded (this install, the one CI builds with), and every shim the
 * generator writes is checked as valid ES-module syntax. jsdom (the default environment) lets the
 * react-dom client build load.
 */
import { readFileSync } from 'fs'
import { createRequire } from 'module'
import path from 'path'
import ts from 'typescript'
import { describe, expect, it } from 'vitest'

import sharedModules from '../shared-modules.json'

interface ShimEntry {
  readonly specifier: string
  readonly file: string
  readonly names: string[]
}

interface ShimGenerator {
  exportNamesFrom(sourceText: string): string[]
  sharedModuleExports(frontendRoot: string): ShimEntry[]
  renderShim(entry: { readonly specifier: string }, names: readonly string[], hostGlobal: string): string
}

const load = createRequire(import.meta.url)
const GENERATOR_PATH = load.resolve('../../../scripts/theme-sdk/generate-shims.js')
const generator = load(GENERATOR_PATH) as ShimGenerator
const FRONTEND = path.resolve(__dirname, '../../..')
const SKIPPED = new Set(['default', '__esModule'])
const IDENTIFIER = /^[A-Za-z_$][\w$]*$/

const BUILD_FILES: string[] = sharedModules.modules.flatMap((entry) => (entry as { from?: string[] }).from ?? [])

function liveNames(file: string): string[] {
  const exported = load(load.resolve(file, { paths: [FRONTEND] })) as Record<string, unknown>
  return Object.keys(exported).filter((name) => !SKIPPED.has(name)).sort()
}

function namesFor(specifier: string): string[] {
  const entry = generator.sharedModuleExports(FRONTEND).find((candidate) => candidate.specifier === specifier)
  expect(entry, specifier).toBeDefined()
  return entry?.names ?? []
}

function syntaxErrors(source: string): string[] {
  const output = ts.transpileModule(source, {
    reportDiagnostics: true,
    fileName: 'shim.js',
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022, allowJs: true },
  })
  return (output.diagnostics ?? []).map((diagnostic) => ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n'))
}

const GOLDEN_TWO_NAME_SHIM = [
  '// Generated by frontend/scripts/theme-sdk/generate-shims.js from the React that Next bundles',
  '// (next/dist/compiled). Do not edit. PRD-261 A-01.',
  'const host = globalThis.__AUTOMATOS_THEME_HOST__;',
  'const shared = host && host.modules ? host.modules["react"] : undefined;',
  'if (!shared) {',
  '  throw new Error(\'Automatos theme host: "react" is not shared on this page.\');',
  '}',
  'export default shared.default ?? shared;',
  'export const {',
  '  useState,',
  '  version,',
  '} = shared;',
  '',
].join('\n')

describe('PRD-261 A-01 — reading export names statically', () => {
  it('lists `exports.<name> =` assignments, sorted and once each, without default or __esModule', () => {
    const source = [
      'exports.b = 1;',
      'exports.a = function () {};',
      'exports.b = 2;',
      'if (exports.c == null) {}',
      'exports.default = 3; exports.__esModule = true;',
      'module.exports.d = 4;',
    ].join('\n')
    expect(generator.exportNamesFrom(source)).toEqual(['a', 'b', 'd'])
  })

  it.each(BUILD_FILES)('reads the same names from %s as it exports when loaded', (file) => {
    const resolved = load.resolve(file, { paths: [FRONTEND] })
    expect(generator.exportNamesFrom(readFileSync(resolved, 'utf8'))).toEqual(liveNames(file))
  })

  it('lists the core names of each shared module', () => {
    expect(namesFor('react')).toEqual(expect.arrayContaining(['useState', 'createElement', 'version']))
    expect(namesFor('react/jsx-runtime')).toEqual(['Fragment', 'jsx', 'jsxs'])
    expect(namesFor('react-dom')).toEqual(expect.arrayContaining(['createPortal']))
    expect(namesFor('react-dom/client')).toEqual(expect.arrayContaining(['createRoot', 'hydrateRoot']))
  })

  it('lists only identifiers, never default', () => {
    for (const entry of generator.sharedModuleExports(FRONTEND)) {
      expect(entry.names.length, entry.specifier).toBeGreaterThan(0)
      expect(entry.names.filter((name) => !IDENTIFIER.test(name) || name === 'default'), entry.specifier).toEqual([])
    }
  })

  // PRD-261 A-10a: the SDK is lib/theme-sdk, reached by its alias; its names come from its surface files.
  it("lists the SDK's own runtime exports for @automatos/theme-sdk", async () => {
    const sdk = (await import('@automatos/theme-sdk')) as Record<string, unknown>
    expect(namesFor('@automatos/theme-sdk')).toEqual(Object.keys(sdk).filter((name) => !SKIPPED.has(name)).sort())
  })

  it("reads Next's bundled React, the one the App Router renders with", () => {
    const react = load(load.resolve('next/dist/compiled/react', { paths: [FRONTEND] })) as { version: string }
    expect(react.version.startsWith('19.')).toBe(true)
  })
})

describe('PRD-261 A-01 — writing a shim', () => {
  it('writes the exact text for a two-name module', () => {
    expect(generator.renderShim({ specifier: 'react' }, ['useState', 'version'], '__AUTOMATOS_THEME_HOST__')).toBe(GOLDEN_TWO_NAME_SHIM)
  })

  it('refuses a specifier or a name it could not write safely', () => {
    expect(() => generator.renderShim({ specifier: 're"act' }, ['useState'], '__AUTOMATOS_THEME_HOST__')).toThrow()
    expect(() => generator.renderShim({ specifier: 'react' }, ['a-b'], '__AUTOMATOS_THEME_HOST__')).toThrow()
    expect(() => generator.renderShim({ specifier: 'react' }, ['useState'], 'host-global')).toThrow()
  })

  it('never serialises a value into the shim text', () => {
    expect(readFileSync(GENERATOR_PATH, 'utf8')).not.toContain('JSON.stringify')
  })

  it('writes valid ES-module syntax for every shared module', () => {
    for (const entry of generator.sharedModuleExports(FRONTEND)) {
      const shim = generator.renderShim(entry, entry.names, sharedModules.hostGlobal)
      expect({ specifier: entry.specifier, errors: syntaxErrors(shim) }).toEqual({ specifier: entry.specifier, errors: [] })
    }
  })
})
